#!/usr/bin/env python3
"""Run a paired real-build pilot using fresh Codex sessions for every WBS leaf."""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import time
from pathlib import Path


ROOT = Path(__file__).resolve().parent
RUNS = ROOT / "runs"
MODEL = "gpt-5.6-luna"
EFFORT = "medium"

CONTEXT = """Build a tiny Python 3 task application using only the standard library.
Work only in the current directory. Implement exactly the assigned leaf; inspect existing files first.
Do not anticipate later leaves or invent compatibility layers. Run all currently available unittest tests.
Do not commit. Keep the implementation small and production-readable.
"""

TASKS = {
    "STORE": """Create task_store.py with an in-memory TaskStore. It assigns increasing integer IDs,
stores task titles, returns stored task records, and lists records in creation order. Add focused tests.""",
    "AUTH": """Create auth.py with a TokenAuthorizer that accepts a configured set of tokens and raises
PermissionError for missing or unknown tokens. Add focused tests. Do not modify unrelated modules.""",
    "API": """Create task_api.py with TaskAPI backed by TaskStore. create_task(title) validates a nonblank
title and returns the newly stored task record as a flat dictionary with id and title. list_tasks() returns
the stored records. Add focused tests for this stated contract.""",
    "REPORT": """Create reporting.py with render_task_report(api), returning newline-separated lines in the
form '<id>: <title>' from api.list_tasks(). Add focused tests using the current TaskAPI contract.""",
    "JOURNEY": """Implement the first end-to-end journey required by test_first_journey.py. The externally
approved API response envelope in that test supersedes the provisional flat API response. Make the smallest
coherent changes needed so every available test passes, updating affected consumers and any unit-test
expectations that assert the superseded provisional response shape. Do not edit test_first_journey.py or
weaken behavioral coverage.""",
}

ORDERS = {
    "legacy_bottom_up": ("STORE", "AUTH", "API", "REPORT", "JOURNEY"),
    "proof_slice_first": ("STORE", "API", "JOURNEY", "AUTH", "REPORT"),
}

JOURNEY_TEST = '''import unittest

from task_api import TaskAPI
from task_store import TaskStore


class FirstJourneyTest(unittest.TestCase):
    def test_create_and_list_share_the_approved_envelope(self):
        api = TaskAPI(TaskStore())
        created = api.create_task("Ship proof")
        self.assertEqual(created, {"task": {"id": 1, "title": "Ship proof"}})
        self.assertEqual(api.list_tasks(), {"tasks": [{"id": 1, "title": "Ship proof"}]})


if __name__ == "__main__":
    unittest.main()
'''


def run(command: list[str], cwd: Path, *, capture: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(command, cwd=cwd, text=True, capture_output=capture)


def init_run(path: Path) -> None:
    path.mkdir(parents=True)
    (path / "README.md").write_text(
        "# Paired scheduler pilot\n\nGenerated by experiments/paired_pilot/run_pilot.py.\n"
    )
    run(["git", "init", "-q"], path)
    run(["git", "config", "user.name", "WBS Pilot"], path)
    run(["git", "config", "user.email", "pilot@example.invalid"], path)
    run(["git", "add", "."], path)
    run(["git", "commit", "-qm", "pilot baseline"], path)


def commit_leaf(path: Path, leaf: str) -> None:
    run(["git", "add", "."], path)
    result = run(["git", "commit", "-qm", f"complete {leaf}"], path)
    if result.returncode != 0:
        raise RuntimeError(f"failed to commit {leaf}: {result.stderr}")


def execute_leaf(path: Path, leaf: str) -> dict:
    if leaf == "JOURNEY":
        (path / "test_first_journey.py").write_text(JOURNEY_TEST)
    prompt = CONTEXT + "\nAssigned leaf:\n" + TASKS[leaf]
    event_path = path / f"codex-{leaf.lower()}.jsonl"
    command = [
        "codex",
        "exec",
        "--ephemeral",
        "--json",
        "--skip-git-repo-check",
        "--approve-for-me",
        "--model",
        MODEL,
        "-c",
        f'model_reasoning_effort="{EFFORT}"',
        "-C",
        str(path),
        prompt,
    ]
    started = time.monotonic()
    result = run(command, path)
    elapsed = round(time.monotonic() - started, 3)
    event_path.write_text(result.stdout)
    if result.returncode != 0:
        raise RuntimeError(
            f"Codex failed for {path.name}/{leaf}:\n{result.stderr}\n{result.stdout[-2000:]}"
        )
    tests = run(["python3", "-m", "unittest", "discover", "-v"], path)
    if tests.returncode != 0:
        raise RuntimeError(f"tests failed for {path.name}/{leaf}:\n{tests.stderr}")
    usage = {}
    for line in result.stdout.splitlines():
        try:
            event = json.loads(line)
        except json.JSONDecodeError:
            continue
        if event.get("type") == "turn.completed":
            usage = event.get("usage", {})
    return {
        "leaf": leaf,
        "elapsed_seconds": elapsed,
        "usage": usage,
        "tests": tests.stderr.count(" ... ok"),
    }


def changed_lines(
    path: Path, from_revision: str, to_revision: str, files: tuple[str, ...]
) -> int:
    result = run(
        ["git", "diff", "--numstat", from_revision, to_revision, "--", *files],
        path,
    )
    total = 0
    for line in result.stdout.splitlines():
        added, deleted, _ = line.split("\t", 2)
        if added.isdigit() and deleted.isdigit():
            total += int(added) + int(deleted)
    return total


def execute_arm(run_root: Path, name: str, order: tuple[str, ...]) -> dict:
    path = run_root / name
    init_run(path)
    leaves = []
    time_to_proof = None
    proof_revision = None
    speculative_revision = None
    for leaf in order:
        if leaf == "JOURNEY":
            speculative_revision = run(["git", "rev-parse", "HEAD"], path).stdout.strip()
        result = execute_leaf(path, leaf)
        commit_leaf(path, leaf)
        leaves.append(result)
        if leaf == "JOURNEY":
            time_to_proof = round(sum(item["elapsed_seconds"] for item in leaves), 3)
            proof_revision = run(["git", "rev-parse", "HEAD"], path).stdout.strip()

    final_tests = run(["python3", "-m", "unittest", "discover", "-v"], path)
    return {
        "strategy": name,
        "order": list(order),
        "time_to_proof_seconds": time_to_proof,
        "total_elapsed_seconds": round(sum(item["elapsed_seconds"] for item in leaves), 3),
        "usage": {
            key: sum(item["usage"].get(key, 0) for item in leaves)
            for key in ("input_tokens", "cached_input_tokens", "output_tokens")
        },
        "journey_changed_lines_in_preexisting_consumers": changed_lines(
            path,
            speculative_revision,
            proof_revision,
            ("auth.py", "reporting.py"),
        ),
        "proof_revision": proof_revision,
        "final_tests_passed": final_tests.returncode == 0,
        "leaves": leaves,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--keep", action="store_true", help="Refuse to replace prior run data")
    parser.add_argument(
        "--first",
        choices=tuple(ORDERS),
        default="legacy_bottom_up",
        help="Strategy to execute first for run-order counterbalancing",
    )
    parser.add_argument(
        "--label",
        default="",
        help="Optional result suffix; also preserves runs in a separately named directory",
    )
    args = parser.parse_args()
    if args.label and not args.label.replace("-", "").replace("_", "").isalnum():
        raise SystemExit("--label may contain only letters, numbers, hyphens, and underscores")
    run_root = ROOT / (f"runs-{args.label}" if args.label else "runs")
    result_path = ROOT / (f"results-{args.label}.json" if args.label else "results.json")
    if run_root.exists():
        if args.keep:
            raise SystemExit(f"Run directory already exists: {run_root}")
        shutil.rmtree(run_root)
    run_root.mkdir(parents=True)

    strategy_names = [args.first] + [name for name in ORDERS if name != args.first]
    results = [execute_arm(run_root, name, ORDERS[name]) for name in strategy_names]
    output = {
        "model": MODEL,
        "reasoning_effort": EFFORT,
        "design": "paired sequential leaf sessions; one run per strategy",
        "execution_order": strategy_names,
        "results": results,
    }
    result_path.write_text(json.dumps(output, indent=2) + "\n")
    print(json.dumps(output, indent=2))


if __name__ == "__main__":
    main()
